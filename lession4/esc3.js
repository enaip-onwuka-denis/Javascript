function somma(a, b) {
    return a + b;
}

function sottrazione(a, b) {
    return a - b;
}

function moltiplicazione(a, b) {
    return a * b;
}

function divisione(a, b) {
    return a / b;
}

console.log(somma(10, 5));
console.log(sottrazione(10, 5));
console.log(moltiplicazione(10, 5));
console.log(divisione(10, 5));

